#!/usr/bin/env python3
"""Generate PLAN.md from project-progress.json; record progress and real check results."""
from __future__ import annotations
import argparse
import fcntl
import json
import subprocess
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'project-progress.json'
TARGET = ROOT / 'PLAN.md'
STATES = ('pending', 'in_progress', 'implemented', 'complete', 'blocked')
LABELS = {'pending':'Remaining', 'in_progress':'In progress', 'implemented':'Implemented; verification remaining', 'complete':'Complete', 'blocked':'Blocked'}


def load():
    return json.loads(SOURCE.read_text())


def generate(data=None):
    data = data or load()
    tasks = data['tasks']
    complete = sum(t['status'] == 'complete' for t in tasks)
    total = len(tasks)
    verified = sum(t['status'] == 'complete' and bool(t.get('verification_task')) for t in tasks)
    verification_total = sum(bool(t.get('verification_task')) for t in tasks)
    lines = ['# 15-AI / NOVA OS — implementation & verification plan', '',
             f'**{complete}/{total} work items complete · {total-complete} remaining · {round(complete/total*100)}% complete**', '',
             f'Verification gates passed: **{verified}/{verification_total}**. Implemented work is not counted complete until its acceptance checks are recorded.', '',
             f"Last progress update: {data['updated_at']}", '',
             f"Current step: **{data['current_step']}**", '',
             'This file is generated by `scripts/progress.py` from `project-progress.json`. Counts and check results update automatically. Edit the JSON or use the progress command; do not edit this generated Markdown.', '',
             '## Work tracker', '',
             '| # | Work item | State | Evidence / remaining acceptance |',
             '|---|---|---|---|']
    for i, task in enumerate(tasks, 1):
        note = (task.get('evidence') or task['acceptance']).replace('|','/').replace('\n',' ')
        lines.append(f"| {i} | {task['title']} | {LABELS[task['status']]} | {note} |")
    lines += ['', '## Execution order', '', *[f'{i+1}. {step}' for i,step in enumerate(data['phases'])], '',
              '## Current setup', '', *[f'- {step}' for step in data['setup']], '',
              '## Actual verification', '',
              'The backend test suite, frontend production build, and browser checks are separate gates. Live model, SMTP, Telegram and Firebase connectivity are only verified by successful real calls; local simulations do not establish live connectivity.', '']
    for task in tasks:
        if task.get('last_check'):
            check = task['last_check']
            lines.append(f"- {task['title']}: {'passed' if check['exit_code'] == 0 else 'failed'} at {check['at']} (exit {check['exit_code']}).")
    for check in data.get('local_checks',[]):
        lines.append(f"- {check['title']}: {'passed' if check['exit_code'] == 0 else 'failed'} at {check['at']} (exit {check['exit_code']}). {check['scope']}")
    if not any(t.get('last_check') for t in tasks) and not data.get('local_checks'):
        lines.append('- No verification gates have been run against the replacement application yet.')
    lines += ['', '## Scope and continuity', '',
              '- Both original roadmap PDFs were reviewed. Groq is the only model provider. Voice input, wake words and voice updates are deferred.',
              '- The workspace was replaced during implementation. Earlier edits that disappeared are not counted as complete.',
              '- Continue on the current application, creating missing files as needed. Backend credentials belong in environment variables; no service-account JSON file is required.',
              '- Env values are filled. Production builds remain gated until live connections pass; UI preview work is authorized first.', '',
              '## Automatic updates', '',
              '```bash', 'python3 scripts/progress.py                   # regenerate counts',
              'python3 scripts/progress.py watch             # regenerate whenever the tracker changes',
              'python3 scripts/progress.py mark queue in_progress --note "Implementing durable worker"',
              'python3 scripts/progress.py run backend-tests -- backend/venv/bin/python -m unittest discover -s backend/tests -v',
              'cd frontend && npm run build                  # records pass/fail and refreshes PLAN.md', '```', '',
              '`run` records the actual command exit code. A failing gate remains blocked; a zero exit code completes that gate. Feature items need implementation evidence and their acceptance checks before they are marked complete.', '']
    output = '\n'.join(lines)
    if not TARGET.exists() or TARGET.read_text() != output:
        temp = TARGET.with_suffix('.md.tmp')
        temp.write_text(output)
        temp.replace(TARGET)
    print(f'{complete}/{total} complete; {total-complete} remaining; verification {verified}/{verification_total}.')


def update(task_id, state, note=None, check=None):
    # Backend checks and frontend builds can finish at the same instant.
    # Serialize the entire read/update/write so neither erases the other's result.
    with (ROOT / '.progress.lock').open('a') as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        return _update(task_id, state, note, check)


def _update(task_id, state, note=None, check=None):
    data = load()
    task = next((t for t in data['tasks'] if t['id'] == task_id), None)
    if task is None:
        raise SystemExit(f'Unknown work item: {task_id}')
    if state == 'complete' and not (note or task.get('evidence')):
        raise SystemExit('Completion needs evidence; provide --note.')
    task['status'] = state
    if note:
        task['evidence'] = note
    if check:
        task['last_check'] = check
    data['updated_at'] = datetime.now(timezone.utc).isoformat(timespec='seconds')
    temp = SOURCE.with_suffix('.json.tmp')
    temp.write_text(json.dumps(data, indent=2)+'\n')
    temp.replace(SOURCE)
    generate(data)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest='action')
    sub.add_parser('watch')
    mark = sub.add_parser('mark')
    mark.add_argument('task_id');mark.add_argument('state', choices=STATES);mark.add_argument('--note')
    run = sub.add_parser('run')
    run.add_argument('task_id');run.add_argument('command', nargs=argparse.REMAINDER)
    args = parser.parse_args()
    if args.action == 'watch':
        last = None
        try:
            while True:
                raw = SOURCE.read_text()
                if raw != last or not TARGET.exists():
                    generate();last = raw
                time.sleep(1)
        except KeyboardInterrupt:
            return 0
    elif args.action == 'mark':
        update(args.task_id,args.state,args.note)
    elif args.action == 'run':
        command = args.command
        if command and command[0] == '--': command = command[1:]
        if not command: parser.error('run requires a command after --')
        # Launch errors and interrupted checks must not leave a completed gate behind.
        update(args.task_id,'in_progress','Verification command running.')
        try:
            code = subprocess.run(command).returncode
        except FileNotFoundError:
            code = 127
        except KeyboardInterrupt:
            code = 130
        update(args.task_id,'complete' if code == 0 else 'blocked',
               'Verification command passed.' if code == 0 else f'Verification failed (exit {code}); fixes or setup remain.',
               {'at':datetime.now(timezone.utc).isoformat(timespec='seconds'),'exit_code':code})
        return code
    else:
        generate()
    return 0


if __name__ == '__main__':
    sys.exit(main())
